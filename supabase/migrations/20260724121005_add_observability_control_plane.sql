insert into public.observability_readiness_state (
  state_key,
  status,
  summary,
  expires_at,
  refresh_lease_until
)
values (
  'current',
  'not_ready',
  jsonb_build_object(
    'checks',
    jsonb_build_object(
      'optional', jsonb_build_object('healthy', 0, 'total', 0),
      'required', jsonb_build_object('healthy', 0, 'total', 0)
    ),
    'durationMs',
    0,
    'status',
    'not_ready'
  ),
  '-infinity'::timestamptz,
  '-infinity'::timestamptz
)
on conflict (state_key) do nothing;

create or replace function public.claim_observability_readiness_refresh(
  p_owner uuid,
  p_lease_seconds integer default 10
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_claimed integer;
begin
  if p_owner is null or p_lease_seconds < 1 or p_lease_seconds > 30 then
    raise exception 'invalid readiness refresh lease';
  end if;

  update public.observability_readiness_state
  set
    refresh_owner = p_owner,
    refresh_lease_until =
      pg_catalog.clock_timestamp() +
      pg_catalog.make_interval(secs => p_lease_seconds),
    updated_at = pg_catalog.clock_timestamp()
  where state_key = 'current'
    and refresh_lease_until <= pg_catalog.clock_timestamp();

  get diagnostics v_claimed = row_count;
  return v_claimed > 0;
end;
$$;

create or replace function public.complete_observability_readiness_refresh(
  p_owner uuid,
  p_status text,
  p_summary jsonb,
  p_ttl_seconds integer
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_updated integer;
begin
  if p_owner is null
    or p_status not in ('not_ready', 'ready')
    or p_ttl_seconds < 1
    or p_ttl_seconds > 300
    or pg_catalog.jsonb_typeof(p_summary) <> 'object'
    or p_summary ->> 'status' is distinct from p_status
  then
    raise exception 'invalid readiness refresh result';
  end if;

  update public.observability_readiness_state
  set
    status = p_status,
    summary = p_summary,
    expires_at =
      pg_catalog.clock_timestamp() +
      pg_catalog.make_interval(secs => p_ttl_seconds),
    refresh_owner = null,
    refresh_lease_until = '-infinity'::timestamptz,
    updated_at = pg_catalog.clock_timestamp()
  where state_key = 'current'
    and refresh_owner = p_owner
    and refresh_lease_until > pg_catalog.clock_timestamp();

  get diagnostics v_updated = row_count;
  return v_updated > 0;
end;
$$;

