create table if not exists public.observability_alert_rules (
  alert_key text primary key,
  metric_kind text not null
    check (metric_kind in ('latest', 'ratio')),
  threshold numeric not null check (threshold >= 0),
  window_seconds integer not null check (window_seconds between 1 and 86400),
  minimum_samples integer not null check (minimum_samples between 1 and 100000),
  severity text not null check (severity in ('warn', 'error')),
  cooldown_seconds integer not null check (cooldown_seconds between 1 and 86400),
  recovery_consecutive_samples integer not null
    check (recovery_consecutive_samples between 1 and 1000),
  owner text not null,
  destination text not null
);

create table if not exists public.observability_alert_samples (
  id bigint generated by default as identity primary key,
  alert_key text not null
    references public.observability_alert_rules(alert_key)
    on update cascade
    on delete restrict,
  value numeric not null check (value >= 0 and value <= 1000000000),
  occurred_at timestamptz not null default now()
);

create index if not exists observability_alert_samples_window_idx
  on public.observability_alert_samples (alert_key, occurred_at desc);

create table if not exists public.observability_alert_state (
  alert_key text primary key
    references public.observability_alert_rules(alert_key)
    on update cascade
    on delete restrict,
  active boolean not null default false,
  consecutive_healthy_samples integer not null default 0
    check (consecutive_healthy_samples >= 0),
  last_triggered_at timestamptz,
  last_recovered_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.observability_alert_events (
  id uuid primary key default gen_random_uuid(),
  alert_key text not null
    references public.observability_alert_rules(alert_key)
    on update cascade
    on delete restrict,
  outcome text not null check (outcome in ('triggered', 'recovered')),
  severity text not null check (severity in ('info', 'warn', 'error')),
  metric_value numeric not null check (metric_value >= 0),
  sample_count integer not null check (sample_count >= 1),
  threshold numeric not null check (threshold >= 0),
  window_seconds integer not null check (window_seconds >= 1),
  destination text not null,
  occurred_at timestamptz not null default now()
);

create index if not exists observability_alert_events_lookup_idx
  on public.observability_alert_events (alert_key, occurred_at desc);

