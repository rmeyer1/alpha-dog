create table if not exists public.observability_readiness_state (
  state_key text primary key,
  status text not null
    check (status in ('not_ready', 'ready')),
  summary jsonb not null,
  expires_at timestamptz not null,
  refresh_owner uuid,
  refresh_lease_until timestamptz not null,
  updated_at timestamptz not null default now(),
  constraint observability_readiness_state_singleton
    check (state_key = 'current'),
  constraint observability_readiness_summary_object
    check (jsonb_typeof(summary) = 'object')
);

alter table public.observability_readiness_state enable row level security;
alter table public.observability_readiness_state force row level security;

